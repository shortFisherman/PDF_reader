export function createAlignmentController({ leftEl, rightEl }) {
    const state = {
        currentTarget: { pageIndex: 0, intraPageOffsetPx: 0 },
        lockSide: null,
    };

    let leftScrollHandler = null;
    let rightScrollHandler = null;

    // Column whose next scroll event should be suppressed — set by realign()
    // right before it writes scrollTop/scrollLeft, cleared by onScroll.
    let suppressNextScrollFrom = null;

    // ---- geometry helpers ----

    // Scroll-content coordinate of an element inside a column.
    function offsetInColumn(el, column) {
        const colRect = column.getBoundingClientRect();
        return el.getBoundingClientRect().top - colRect.top + column.scrollTop;
    }

    // ---- core logic ----

    // Pick the .page-container most visible in the column's viewport.
    function findBestPage(column) {
        const containers = column.querySelectorAll('.page-container');
        if (!containers.length) return null;

        const viewTop = column.scrollTop;
        const viewBottom = viewTop + column.clientHeight;
        let best = null;
        let bestCoverage = 0;

        for (let i = 0; i < containers.length; i++) {
            const c = containers[i];
            const top = offsetInColumn(c, column);
            const bottom = top + c.getBoundingClientRect().height;
            const overlap = Math.min(bottom, viewBottom) - Math.max(top, viewTop);
            if (overlap <= 0) continue;
            const coverage = overlap / c.getBoundingClientRect().height;
            if (coverage > bestCoverage) {
                bestCoverage = coverage;
                best = c;
            }
        }

        return best;
    }

    // Derive (pageIndex, intraPageOffsetPx) from the column's current scrollTop.
    function deriveTarget(column) {
        const bestPage = findBestPage(column);
        if (!bestPage) return null;

        let pageIndex = parseInt(bestPage.dataset.page, 10);
        const selectedTop = offsetInColumn(bestPage, column);
        let intraOffset = column.scrollTop - selectedTop;

        // Cross-page normalization: when the viewport top is above the
        // selected page, roll back to the previous page and re-measure
        // from there.  Use the real inter-page distance (includes CSS
        // margins / gaps) so alignment stays dead-on at boundaries.
        if (intraOffset < 0) {
            var prevSelectionTop = selectedTop;
            pageIndex -= 1;
            var prevPage = column.querySelector('[data-page="' + pageIndex + '"]');
            if (prevPage) {
                var prevTop = offsetInColumn(prevPage, column);
                intraOffset += prevSelectionTop - prevTop;
            }
        }

        return { pageIndex: pageIndex, intraOffset: intraOffset };
    }

    // Copy horizontal scroll from the lock-side column to another column
    // using proportional sync (page widths are identical across columns).
    function syncHorizontal(column) {
        const srcEl = state.lockSide === 'left' ? leftEl
                    : state.lockSide === 'right' ? rightEl
                    : null;
        if (!srcEl || srcEl === column) return;
        if (srcEl.scrollWidth <= srcEl.clientWidth) return;
        if (column.scrollWidth <= column.clientWidth) return;

        const ratio = srcEl.scrollLeft / (srcEl.scrollWidth - srcEl.clientWidth);
        column.scrollLeft = ratio * (column.scrollWidth - column.clientWidth);
    }

    // ---- public API ----

    function realign(column) {
        const pageContainer = column.querySelector('[data-page="' + state.currentTarget.pageIndex + '"]');
        if (!pageContainer) return;

        // Prevent the scroll events generated by the writes below from
        // re-entering onScroll and triggering an echo loop.
        suppressNextScrollFrom = column;

        column.scrollTop = offsetInColumn(pageContainer, column)
                         + state.currentTarget.intraPageOffsetPx;

        syncHorizontal(column);
    }

    function onScroll(src) {
        // Ignore scroll events that realign() itself generated.
        if (suppressNextScrollFrom === src) {
            suppressNextScrollFrom = null;
            return;
        }
        suppressNextScrollFrom = null;

        const target = deriveTarget(src);
        if (!target) return;

        state.currentTarget.pageIndex = target.pageIndex;
        state.currentTarget.intraPageOffsetPx = target.intraOffset;
        state.lockSide = src === leftEl ? 'left' : 'right';

        const dst = state.lockSide === 'left' ? rightEl : leftEl;
        realign(dst);
    }

    function onImageLoaded(_side, _pageIndex) {
        realign(leftEl);
        realign(rightEl);
    }

    function onZoomChange(newZoom, oldZoom) {
        state.currentTarget.intraPageOffsetPx *= newZoom / oldZoom;
        realign(leftEl);
        realign(rightEl);
    }

    function setLockTarget(pageIndex, offsetPx) {
        state.currentTarget.pageIndex = pageIndex;
        state.currentTarget.intraPageOffsetPx = offsetPx;
    }

    function getLockTarget() {
        const t = state.currentTarget;
        return { pageIndex: t.pageIndex, intraPageOffsetPx: t.intraPageOffsetPx };
    }

    function installScrollListeners() {
        leftScrollHandler = function () { onScroll(leftEl); };
        rightScrollHandler = function () { onScroll(rightEl); };
        leftEl.addEventListener('scroll', leftScrollHandler);
        rightEl.addEventListener('scroll', rightScrollHandler);
    }

    function dispose() {
        if (leftScrollHandler) {
            leftEl.removeEventListener('scroll', leftScrollHandler);
            leftScrollHandler = null;
        }
        if (rightScrollHandler) {
            rightEl.removeEventListener('scroll', rightScrollHandler);
            rightScrollHandler = null;
        }
    }

    return {
        onScroll,
        onImageLoaded,
        onZoomChange,
        realign,
        setLockTarget,
        getLockTarget,
        installScrollListeners,
        dispose,
    };
}
